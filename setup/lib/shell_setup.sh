#!/bin/zsh
# filepath: setup/lib/shell_setup.sh

ensure_shell_repository() (
    local target="$1" primary="$2" mirror="$3" required="$4"
    if [[ -e "$target" || -L "$target" ]]; then
        if [[ -f "$target/$required" ]] && git -C "$target" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
            info "已有仓库可用，跳过安装: $target"
            return 0
        fi
        error "已有目录不完整，已保留；请检查后移走该目录再重试: $target"
        return 1
    fi
    mkdir -p "${target:h}" || return 1
    local staging
    staging="$(mktemp -d "${target}.clone.XXXXXXXX")" || return 1
    trap 'rm -rf "$staging"' EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM HUP
    if ! git clone --depth=1 "$primary" "$staging/primary"; then
        warning "官方克隆失败，尝试镜像。"
        git clone --depth=1 "$mirror" "$staging/mirror" || return 1
        [[ -f "$staging/mirror/$required" ]] || return 1
        [[ ! -e "$target" && ! -L "$target" ]] || return 1
        mv "$staging/mirror" "$target" || return 1
    else
        [[ -f "$staging/primary/$required" ]] || return 1
        [[ ! -e "$target" && ! -L "$target" ]] || return 1
        mv "$staging/primary" "$target" || return 1
    fi
)

install_oh_my_zsh() {
    ensure_shell_repository "$HOME/.oh-my-zsh" https://github.com/ohmyzsh/ohmyzsh.git https://gitee.com/mirrors/oh-my-zsh.git oh-my-zsh.sh
}

install_p10k_theme() {
    ensure_shell_repository "${ZSH_CUSTOM:-$HOME/.oh-my-zsh/custom}/themes/powerlevel10k" https://github.com/romkatv/powerlevel10k.git https://gitee.com/romkatv/powerlevel10k.git powerlevel10k.zsh-theme
}

install_plugins() {
    local plugin
    for plugin in zsh-syntax-highlighting zsh-autosuggestions; do
        ensure_shell_repository "${ZSH_CUSTOM:-$HOME/.oh-my-zsh/custom}/plugins/$plugin" "https://github.com/zsh-users/$plugin.git" "https://gitee.com/mirrors/$plugin.git" "$plugin.plugin.zsh" || return 1
    done
}

update_zsh_config() {
    local content
    content="$(cat <<'CONFIG'
export ZSH="${ZSH:-$HOME/.oh-my-zsh}"
ZSH_THEME="${ZSH_THEME:-powerlevel10k/powerlevel10k}"
typeset -ga plugins
typeset -U plugins
plugins=("${plugins[@]}" git extract z colored-man-pages zsh-syntax-highlighting zsh-autosuggestions)
(( ${+POWERLEVEL9K_LEFT_PROMPT_ELEMENTS} )) || typeset -ga POWERLEVEL9K_LEFT_PROMPT_ELEMENTS=(dir vcs status)
(( ${+POWERLEVEL9K_RIGHT_PROMPT_ELEMENTS} )) || typeset -ga POWERLEVEL9K_RIGHT_PROMPT_ELEMENTS=(time background_jobs)
POWERLEVEL9K_MODE="${POWERLEVEL9K_MODE:-nerdfont-complete}"
if ! typeset -f omz >/dev/null 2>&1; then
    source "$ZSH/oh-my-zsh.sh"
fi
CONFIG
)" || return 1
    # 沿用旧标记，原位更新；不再注释或覆盖用户自己的配置。
    write_managed_block "$HOME/.zshrc" 'Oh My Zsh & P10k' script "$content" false 'generated by'
}

font_is_valid() {
    [[ -s "$1" ]] || return 1
    local magic size count directory_size
    magic="$(od -An -tx1 -N4 "$1" | tr -d ' \n')" || return 1
    [[ "$magic" == 00010000 || "$magic" == 4f54544f ]] || return 1
    size="$(stat -f '%z' "$1")" || return 1
    (( size >= 12 )) || return 1
    count="$(od -An -tu1 -j4 -N2 "$1" | awk 'NF {print $1*256+$2}')" || return 1
    (( count > 0 && count <= 4096 )) || return 1
    directory_size=$((12 + count * 16))
    (( directory_size <= size )) || return 1
    # 校验每张字体表的偏移与长度，防止仅有正确文件头的半成品被跳过。
    od -An -tu1 -N "$directory_size" "$1" | awk -v size="$size" -v tables="$count" '
      {for(i=1;i<=NF;i++) bytes[++n]=$i}
      function uint32(i) {return bytes[i]*16777216+bytes[i+1]*65536+bytes[i+2]*256+bytes[i+3]}
      END {for(t=0;t<tables;t++) {i=13+t*16; offset=uint32(i+8); table_length=uint32(i+12); if(offset<12+tables*16 || table_length<1 || offset+table_length>size) exit 1}}
    '
}

install_one_font() (
    local destination="$1" url="$2" temporary
    font_is_valid "$destination" && return 0
    [[ ! -L "$destination" ]] || { error "字体路径是符号链接，请先检查: $destination"; return 1; }
    mkdir -p "${destination:h}" || return 1
    temporary="$(mktemp "${destination}.download.XXXXXXXX")" || return 1
    trap 'rm -f "$temporary"' EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM HUP
    curl -fL --connect-timeout 10 --max-time 120 -o "$temporary" "$url" || return 1
    font_is_valid "$temporary" || { error "下载字体格式无效: $destination"; return 1; }
    chmod 644 "$temporary" && mv -f "$temporary" "$destination"
)

install_fonts() {
    local name encoded
    for name in 'MesloLGS NF Regular.ttf' 'MesloLGS NF Bold.ttf' 'MesloLGS NF Italic.ttf' 'MesloLGS NF Bold Italic.ttf'; do
        encoded="${name// /%20}"
        install_one_font "$HOME/Library/Fonts/$name" "https://github.com/romkatv/powerlevel10k-media/raw/master/$encoded" || return 1
    done
}
